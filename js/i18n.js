/**
 * Name des gerade aktiven Cloud-Dienstes. Viele Texte gelten für beide
 * Anbieter – früher stand dort fest "Google Drive", auch wenn man mit
 * Microsoft angemeldet war.
 */
function cloudProviderLabel() {
  try {
    if (typeof getActiveProvider === 'function') return getActiveProvider().label;
  } catch (e) { /* js/common.js noch nicht geladen */ }
  return 'Google Drive';
}

function t(k) {
  const text = T[lang][k] || k;
  if (typeof text === 'string' && text.includes('{provider}')) {
    return text.split('{provider}').join(cloudProviderLabel());
  }
  return text;
}

function tf(k, vars) {
  const base = t(k);
  return base.replace(/\{(\w+)\}/g, (_, key) => vars[key] || '');
}

