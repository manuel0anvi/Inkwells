// Current language
let _currentLang = 'en';

/**
 * Name des gerade eingestellten Cloud-Anbieters ("Google Drive" / "OneDrive").
 * Wird gebraucht, weil viele Texte beide Dienste bedienen müssen – früher
 * stand dort fest "Google Drive", auch wenn man mit Microsoft angemeldet war.
 */
function cloudProviderLabel() {
  try {
    if (typeof CloudSync_ !== 'undefined' && CloudSync_?.providerLabel) {
      return CloudSync_.providerLabel();
    }
    const stored = (typeof Settings !== 'undefined' && Settings?.get) ? Settings.get('cloudProvider') : '';
    if (stored === 'microsoft') return 'OneDrive';
  } catch (e) { /* zu früh im Start – dann der Standard unten */ }
  return 'Google Drive';
}

// Get translation
function t(key) {
  const lang = TRANSLATIONS[_currentLang] || TRANSLATIONS.de;
  const text = lang[key] || TRANSLATIONS.de[key] || key;
  if (typeof text === 'string' && text.includes('{provider}')) {
    return text.split('{provider}').join(cloudProviderLabel());
  }
  return text;
}

// Set language
function setLanguage(lang) {
  if (TRANSLATIONS[lang]) {
    _currentLang = lang;
    applyTranslations();
  }
}

// Get current language
function getLanguage() {
  return _currentLang;
}

// Apply translations to all UI elements
function applyTranslations() {
  // Elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (el.tagName === 'INPUT' && el.placeholder !== undefined) {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  
  // Elements with data-i18n-title attribute (for tooltips)
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });

  // Platzhaltertexte. Wurde bisher nirgends ausgewertet – die Suchleiste auf
  // der Startseite blieb dadurch in jeder Sprache deutsch.
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  
  // Update dynamic content
  if (typeof renderHomeGrid === 'function' && E('view-home').style.display !== 'none') {
    renderHomeGrid();
  }
  if (typeof renderSideTree === 'function' && S.activeNbId) {
    renderSideTree();
  }
  
  _appliedProviderLabel = cloudProviderLabel();

  window.dispatchEvent(new Event('language-changed'));
  console.log('[i18n] Language set to:', _currentLang);
}

/**
 * Nach einem Anbieterwechsel stehen in den festen Texten (data-i18n) noch
 * die Namen des alten Dienstes. Einmal neu übersetzen, aber nur wenn sich
 * der Name wirklich geändert hat – applyTranslations() zeichnet viel neu.
 */
let _appliedProviderLabel = null;

function refreshProviderTexts() {
  const label = cloudProviderLabel();
  if (label === _appliedProviderLabel) return;
  applyTranslations();
}

// Ensure the initial UI is translated on first paint (uses current default language)
document.addEventListener('DOMContentLoaded', () => {
  try { applyTranslations(); } catch (e) { console.warn('[i18n] initial apply failed', e); }
});
